"""A. Migrations: upgrade from empty, reversible downgrade, models == migration."""

from __future__ import annotations

import asyncio

import pytest
import sqlalchemy as sa
from alembic import command

from server.tests.db.conftest import APP_TABLES

EXPECTED_VIEWS = {"player_box_scores", "game_team_scores"}
EXPECTED_TRIGGERS = {
    "trg_10_participant_count",
    "trg_20_participant_notify",
    "trg_games_guard_participant_count",
    "trg_games_notify",
    "trg_processing_jobs_notify",
    "trg_recordings_require_recorded_game",
}


@pytest.fixture(autouse=True)
async def _reset_pooled_connections(pooled_engine):
    # Dropping and recreating enum types gives them new OIDs; pooled asyncpg
    # connections would keep stale type caches, so start them fresh afterwards.
    yield
    await pooled_engine.dispose()


async def _catalog(engine) -> dict[str, set[str]]:
    async with engine.connect() as conn:
        tables = set(
            (await conn.execute(sa.text(
                "SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename <> 'spatial_ref_sys'"
            ))).scalars()
        )
        views = set((await conn.execute(sa.text(
            "SELECT viewname FROM pg_views WHERE schemaname = 'public' "
            "AND viewname NOT IN ('geometry_columns', 'geography_columns')"
        ))).scalars())
        triggers = set((await conn.execute(sa.text(
            "SELECT tgname FROM pg_trigger WHERE NOT tgisinternal"
        ))).scalars())
        functions = set((await conn.execute(sa.text(
            "SELECT proname FROM pg_proc WHERE proname LIKE 'pickup\\_%'"
        ))).scalars())
        enums = set((await conn.execute(sa.text(
            "SELECT t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace "
            "WHERE n.nspname = 'public' AND t.typtype = 'e'"
        ))).scalars())
    return {"tables": tables, "views": views, "triggers": triggers, "functions": functions, "enums": enums}


async def test_upgrade_head_on_empty_database(alembic_cfg, engine):
    await asyncio.to_thread(command.downgrade, alembic_cfg, "base")
    empty = await _catalog(engine)
    assert empty["tables"] <= {"alembic_version"}
    await asyncio.to_thread(command.upgrade, alembic_cfg, "head")
    cat = await _catalog(engine)
    assert set(APP_TABLES) | {"alembic_version"} == cat["tables"]
    assert EXPECTED_VIEWS <= cat["views"]
    assert EXPECTED_TRIGGERS <= cat["triggers"]


async def test_downgrade_then_upgrade_is_reversible(alembic_cfg, engine):
    await asyncio.to_thread(command.downgrade, alembic_cfg, "base")
    cat = await _catalog(engine)
    assert cat["tables"] <= {"alembic_version"}
    assert not cat["views"] & EXPECTED_VIEWS
    assert not cat["functions"], f"leftover functions: {cat['functions']}"
    assert not cat["enums"], f"leftover enum types: {cat['enums']}"
    await asyncio.to_thread(command.upgrade, alembic_cfg, "head")
    assert set(APP_TABLES) <= (await _catalog(engine))["tables"]


